import fs from 'node:fs';
import path from 'node:path';
import { JSDOM } from 'jsdom';
import { CANONICAL_ORIGIN, RETIRED_HOSTNAMES, resolveSite } from '../src/lib/siteConfig';

const distDir = path.resolve(process.cwd(), 'dist');
const site = resolveSite({
  SITE_URL: process.env.SITE_URL,
  VERCEL_ENV: process.env.VERCEL_ENV,
  VERCEL_URL: process.env.VERCEL_URL,
});
const errors: string[] = [];

/** Any hostname that must never appear in generated output. */
const retiredHostnames = [...RETIRED_HOSTNAMES, 'localhost', '127.0.0.1'];

function collectHtmlFiles(directory: string): string[] {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const entryPath = path.join(directory, entry.name);
    return entry.isDirectory() ? collectHtmlFiles(entryPath) : entry.name.endsWith('.html') ? [entryPath] : [];
  });
}

function pagePathFromFile(file: string): string {
  const relative = path.relative(distDir, file).replace(/\\/g, '/');
  if (relative === 'index.html') return '/';
  return `/${relative.replace(/\.html$/, '')}`;
}

function fileForPagePath(pagePath: string): string {
  const relative = pagePath === '/' ? 'index.html' : `${pagePath.slice(1)}.html`;
  const file = path.resolve(distDir, relative);
  if (!file.startsWith(`${distDir}${path.sep}`) && file !== path.join(distDir, 'index.html')) {
    throw new Error(`Page path escapes the build output directory: ${pagePath}`);
  }
  return file;
}

function addError(message: string) {
  errors.push(message);
}

/**
 * Lightweight tag extraction.
 *
 * The audit used to parse all 620 generated pages with JSDOM. Each parsed document
 * lives on the heap until GC runs, and the whole run peaked at the Node heap limit
 * (~4 GB) — it passed only by a small margin, then began failing with
 * "JavaScript heap out of memory" as the catalogue grew. The checks below only
 * need titles, meta tags, link tags and anchors, so they are read directly from the
 * markup instead. Same assertions, no document tree.
 */
function findTags(html: string, tagName: string): string[] {
  return [...html.matchAll(new RegExp(`<${tagName}\\b[^>]*>`, 'gi'))].map((match) => match[0]);
}

function attribute(tag: string, name: string): string | undefined {
  return tag.match(new RegExp(`\\b${name}="([^"]*)"`, 'i'))?.[1];
}

/** Content of every `<meta>` whose name/property matches `key`. */
function metaContent(html: string, attributeName: 'name' | 'property', key: string): string[] {
  return findTags(html, 'meta')
    .filter((tag) => attribute(tag, attributeName) === key)
    .map((tag) => attribute(tag, 'content') ?? '');
}

if (!fs.existsSync(distDir)) {
  throw new Error('Build output directory "dist" does not exist.');
}

const sitemapPath = path.join(distDir, 'sitemap.xml');
const robotsPath = path.join(distDir, 'robots.txt');
if (!fs.existsSync(sitemapPath) || !fs.existsSync(robotsPath)) {
  throw new Error('Expected prerendered sitemap.xml and robots.txt in dist.');
}

const sitemapXml = fs.readFileSync(sitemapPath, 'utf8');

/**
 * `public/` is copied into `dist/` verbatim by Vite before prerender runs. A
 * hand-maintained sitemap or robots file in `public/` is therefore a stale asset
 * waiting to overwrite (or linger alongside) the generated one — the classic
 * "successful build, wrong deployment" cause. Refuse to build with one present.
 */
const publicDir = path.resolve(process.cwd(), 'public');
if (fs.existsSync(publicDir)) {
  for (const name of fs.readdirSync(publicDir)) {
    if (/^sitemap(-\d+)?\.xml$/.test(name) || name === 'robots.txt') {
      addError(
        `public/${name} must not exist: sitemap.xml and robots.txt are generated by scripts/prerender.ts. ` +
          'Delete the static copy so it cannot overwrite the generated file.'
      );
    }
  }
}

/**
 * The canonical production build must use CANONICAL_ORIGIN exactly. A non-preview
 * build that resolves elsewhere is the migration defect that put
 * `calculate-daily.vercel.app` URLs in production, so it is an error, not a note.
 */
if (!site.isPreview && site.url !== CANONICAL_ORIGIN) {
  addError(
    `Non-preview build resolved origin ${site.url}, expected ${CANONICAL_ORIGIN}. ` +
      'Canonical URLs, og:url, JSON-LD and the sitemap would all contradict the canonical domain.'
  );
}
if (site.isPreview && site.url === CANONICAL_ORIGIN) {
  addError('Preview build must not claim the canonical production origin.');
}

/** A URL is stale when it points at a retired host or plain HTTP. */
const staleUrlReason = (value: string): string | undefined => {
  let parsed: URL;
  try {
    parsed = new URL(value);
  } catch {
    return 'not an absolute URL';
  }
  if (retiredHostnames.includes(parsed.hostname.toLowerCase())) {
    return `retired host ${parsed.hostname}`;
  }
  if (parsed.protocol === 'http:' && !site.isPreview) {
    return 'plain HTTP instead of HTTPS';
  }
  return undefined;
};

const isSitemapIndex = /<sitemapindex[\s>]/.test(sitemapXml);

/**
 * Flatten `sitemap.xml` into the URL set it advertises. A single `<urlset>` is
 * used below the protocol limits; above them the file is a `<sitemapindex>` of
 * child files, each of which must exist and be readable.
 */
function flattenSitemap(xml: string, depth = 0): string[] {
  const locs = [...xml.matchAll(/<loc>([^<]+)<\/loc>/g)].map((match) => match[1]);
  if (!/<sitemapindex[\s>]/.test(xml)) return locs;
  if (depth > 2) {
    addError('Nested sitemap index (an index inside an index) is not supported.');
    return [];
  }
  const childUrls: string[] = [];
  for (const childUrl of locs) {
    const childPath = path.join(distDir, new URL(childUrl).pathname.replace(/^\//, ''));
    if (!fs.existsSync(childPath)) {
      addError(`Sitemap index references a missing file: ${childUrl}`);
      continue;
    }
    childUrls.push(...flattenSitemap(fs.readFileSync(childPath, 'utf8'), depth + 1));
  }
  return childUrls;
}

const sitemapUrls = flattenSitemap(sitemapXml);
const sitemapSet = new Set(sitemapUrls);
const duplicateUrls = sitemapUrls.filter((url, index) => sitemapUrls.indexOf(url) !== index);
if (duplicateUrls.length) addError(`Duplicate sitemap URLs: ${[...new Set(duplicateUrls)].join(', ')}`);
if (site.isPreview && sitemapUrls.length) addError('Preview sitemap must not contain URLs.');
if (!site.isPreview && !sitemapUrls.length) addError('Non-preview sitemap unexpectedly contains no URLs.');
if (!/xmlns="http:\/\/www\.sitemaps\.org\/schemas\/sitemap\/0\.9"/.test(sitemapXml)) {
  addError('Sitemap is missing the sitemaps.org 0.9 XML namespace.');
}
if (sitemapUrls.length > 50_000 && !isSitemapIndex) {
  addError(`Sitemap lists ${sitemapUrls.length} URLs without a sitemap index (protocol limit 50,000).`);
}

/**
 * <lastmod> must reflect a real content change. The previous generator stamped
 * the build date on all 316 URLs, which teaches crawlers to ignore the field.
 * Detect that regression precisely: every URL sharing one value that equals today.
 */
const lastmods = [...sitemapXml.matchAll(/<lastmod>([^<]*)<\/lastmod>/g)].map((m) => m[1].trim());
const today = new Date().toISOString().slice(0, 10);
for (const value of lastmods) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(value)) {
    addError(`Sitemap lastmod is not a YYYY-MM-DD date: "${value}"`);
    continue;
  }
  if (value > today) addError(`Sitemap lastmod is in the future: ${value}`);
}
if (lastmods.length > 1) {
  const unique = new Set(lastmods);
  if (unique.size === 1 && [...unique][0] === today) {
    addError(
      `Every sitemap <lastmod> is today's build date (${today}). ` +
        'Sitemap lastmod must come from content dates, not the build timestamp.'
    );
  }
}

// Every listed URL must carry a content date, so no page silently drops the
// signal (that is how the hand-written and listing pages went undated).
const urlEntries = [...sitemapXml.matchAll(/<url>\s*([\s\S]*?)<\/url>/g)].map((m) => m[1]);
const undated = urlEntries.filter((entry) => !/<lastmod>/.test(entry));
if (!site.isPreview && undated.length) {
  const examples = undated
    .slice(0, 5)
    .map((entry) => entry.match(/<loc>([^<]*)<\/loc>/)?.[1] ?? '(unparseable url)')
    .join(', ');
  addError(
    `${undated.length} of ${urlEntries.length} sitemap URLs have no <lastmod> (e.g. ${examples}). ` +
      'Give the page a content date instead of dropping the field.'
  );
}

const robotsTxt = fs.readFileSync(robotsPath, 'utf8');
if (site.isPreview && !/Disallow:\s*\/\s*(?:\r?\n|$)/m.test(robotsTxt)) {
  addError('Preview robots.txt must disallow crawling.');
}
if (!site.isPreview && /Disallow:\s*\/\s*(?:\r?\n|$)/m.test(robotsTxt)) {
  addError('Non-preview robots.txt must not disallow the entire site.');
}

for (const url of sitemapUrls) {
  let parsed: URL;
  try {
    parsed = new URL(url);
  } catch {
    addError(`Invalid sitemap URL: ${url}`);
    continue;
  }
  if (parsed.origin !== site.url) {
    addError(`Sitemap URL uses ${parsed.origin}, expected ${site.url}: ${url}`);
    continue;
  }
  const urlDefect = staleUrlReason(url);
  if (urlDefect) {
    addError(`Sitemap URL is not deployable (${urlDefect}): ${url}`);
  }
  if (parsed.search || parsed.hash || (parsed.pathname !== '/' && parsed.pathname.endsWith('/'))) {
    addError(`Sitemap URL is not in preferred canonical format: ${url}`);
  }

  const file = fileForPagePath(parsed.pathname);
  if (!fs.existsSync(file)) {
    addError(`Sitemap URL has no prerendered page: ${url} (${path.relative(distDir, file)})`);
  }
  // The canonical / og:url / noindex checks for this page happen in the per-page
  // pass below, which already has the parsed document. Parsing every sitemap URL a
  // second time here doubled the script's memory for no extra coverage — and with
  // 620 pages that second copy was enough to exhaust the heap.
}

/**
 * Meta descriptions collected per page, so duplicate snippets can be detected
 * after the per-page pass. The prerenderer previously failed to replace the
 * shell's description at all, which shipped one identical description on all 620
 * pages and passed every other check.
 */
/** Descriptions of indexable pages only — these must be unique. */
const indexableDescriptions = new Map<string, string>();
const SHELL_DESCRIPTION =
  'Free online calculators and unit converters for math, finance, health, construction, cooking, and everyday life. Fast browser-based tools with worked examples.';

const htmlFiles = collectHtmlFiles(distDir);
for (const file of htmlFiles) {
  const relative = path.relative(distDir, file).replace(/\\/g, '/');
  const rawHtml = fs.readFileSync(file, 'utf8');
  const pagePath = relative === '404.html' ? '/404.html' : pagePathFromFile(file);
  const url = `${site.url}${pagePath}`;
  const is404 = relative === '404.html';
  const isListed = sitemapSet.has(url);
  const pageTitle = (rawHtml.match(/<title>([\s\S]*?)<\/title>/i)?.[1] ?? '').trim();
  const robots = metaContent(rawHtml, 'name', 'robots');
  const noindex = robots.some((content) => content.toLowerCase().includes('noindex'));
  const canonicals = findTags(rawHtml, 'link')
    .filter((tag) => attribute(tag, 'rel') === 'canonical')
    .map((tag) => attribute(tag, 'href') ?? '');

  // Public-facing generated HTML must never mention a retired production host, in
  // any attribute, script or JSON-LD payload.
  for (const retired of RETIRED_HOSTNAMES) {
    if (rawHtml.includes(retired)) {
      addError(`Generated HTML still references the retired domain ${retired}: ${relative}`);
    }
  }

  const descriptionMeta = (metaContent(rawHtml, 'name', 'description')[0] ?? '').trim();
  if (!pageTitle || !descriptionMeta) {
    addError(`Missing title or meta description: ${relative}`);
  } else {
    // The shell default is only correct on the home page. Seeing it elsewhere means
    // the description tag was never rewritten for that page.
    if (descriptionMeta === SHELL_DESCRIPTION && relative !== 'index.html') {
      addError(`Page kept the shell's description instead of its own: ${relative}`);
    }
    const ogDescription = (metaContent(rawHtml, 'property', 'og:description')[0] ?? '').trim();
    if (ogDescription && ogDescription !== descriptionMeta) {
      addError(`og:description does not match meta description: ${relative}`);
    }
    const twitterDescription = (metaContent(rawHtml, 'name', 'twitter:description')[0] ?? '').trim();
    if (twitterDescription && twitterDescription !== descriptionMeta) {
      addError(`twitter:description does not match meta description: ${relative}`);
    }
  }

  if (site.isPreview || is404 || !isListed) {
    if (!noindex || robots.length !== 1) addError(`Expected exactly one noindex tag: ${relative}`);
    if (canonicals.length) addError(`Noindex page must not have a canonical: ${relative}`);
    if (isListed) addError(`Non-indexable page appears in sitemap: ${relative}`);
  } else {
    if (noindex) addError(`Indexable page is marked noindex: ${relative}`);
    if (descriptionMeta) {
      indexableDescriptions.set(relative, descriptionMeta);
      if (descriptionMeta.length < 70 || descriptionMeta.length > 160) {
        addError(
          `Indexable page description is ${descriptionMeta.length} characters (allowed 70-160): ${relative}`
        );
      }
    }
    if (canonicals.length !== 1 || canonicals[0] !== url) {
      addError(`Indexable page canonical is missing, duplicated, or incorrect: ${relative}`);
    }
    const ogUrl = (metaContent(rawHtml, 'property', 'og:url')[0] ?? '').trim();
    if (ogUrl !== url) {
      addError(`Indexable page og:url is missing or incorrect: ${relative}`);
    }
    if (ogUrl) {
      const defect = staleUrlReason(ogUrl);
      if (defect) addError(`Indexable page og:url is not deployable (${defect}): ${relative}`);
    }
  }

  if (relative === 'index.html' && !site.isPreview) {
    const jsonLdBlocks = [
      ...rawHtml.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/gi),
    ].map((match) => match[1]);
    const websiteSchemas = jsonLdBlocks.flatMap((block) => {
      try {
        const data = JSON.parse(block || 'null');
        return data?.['@type'] === 'WebSite' ? [data] : [];
      } catch {
        addError('Homepage contains invalid JSON-LD.');
        return [];
      }
    });
    if (websiteSchemas.length !== 1 || websiteSchemas[0]?.url !== `${site.url}/`) {
      addError('Homepage must contain exactly one WebSite schema with an absolute canonical URL.');
    }
  }

  for (const tag of findTags(rawHtml, 'a')) {
    const href = attribute(tag, 'href') || '';
    if (!href || href.startsWith('#') || href.startsWith('//')) continue;
    let target: URL;
    try {
      target = new URL(href, `${site.url}/`);
    } catch {
      addError(`Invalid link in ${relative}: ${href}`);
      continue;
    }
    if (target.origin !== site.url || path.extname(target.pathname)) continue;
    if (target.pathname !== '/' && target.pathname.endsWith('/')) {
      addError(`Internal link is not in preferred URL format in ${relative}: ${href}`);
      continue;
    }
    if (!fs.existsSync(fileForPagePath(target.pathname))) {
      addError(`Internal link has no prerendered destination in ${relative}: ${href}`);
    }
  }
}

/**
 * Embed shells must exist for every indexable calculator and must stay out of
 * the sitemap. A missing file breaks a third-party iframe with a 404, and the
 * generic link check cannot catch it because an iframe `src` is not an anchor.
 * The shell must also carry the attribution link back to the canonical page.
 */
const embedSlugs = sitemapUrls
  .map((url) => new URL(url).pathname)
  .filter((pagePath) => pagePath.startsWith('/calculators/'))
  .map((pagePath) => pagePath.slice('/calculators/'.length));

for (const slug of embedSlugs) {
  const embedFile = path.join(distDir, 'embed', `${slug}.html`);
  if (!fs.existsSync(embedFile)) {
    addError(`Indexable calculator has no prerendered embed shell: /embed/${slug}`);
    continue;
  }
  const embedHtml = fs.readFileSync(embedFile, 'utf8');
  const hasAttribution = findTags(embedHtml, 'a').some(
    (tag) => attribute(tag, 'href') === `/calculators/${slug}`
  );
  if (!hasAttribution) {
    addError(`Embed shell has no attribution link to /calculators/${slug}`);
  }
  if (sitemapSet.has(`${site.url}/embed/${slug}`)) {
    addError(`Embed shell appears in the sitemap: /embed/${slug}`);
  }
}

const notFound = path.join(distDir, '404.html');
if (!fs.existsSync(notFound)) {
  addError('Missing generated 404.html.');
} else {
  const notFoundHtml = fs.readFileSync(notFound, 'utf8');
  const notFoundNoindex = metaContent(notFoundHtml, 'name', 'robots').some((content) =>
    content.toLowerCase().includes('noindex')
  );
  const notFoundCanonical = findTags(notFoundHtml, 'link').some(
    (tag) => attribute(tag, 'rel') === 'canonical'
  );
  if (!notFoundNoindex || notFoundCanonical) {
    addError('404.html must be noindex and must not have a canonical.');
  }
}

// Duplicate meta descriptions split a page's snippet signal across two URLs.
// Indexable pages must be individually distinct: two indexable pages sharing a
// description means one of them is redundant. Noindex shells (embeds, the 404)
// are exempt — they are not competing for a snippet.
{
  const pagesByDescription = new Map<string, string[]>();
  for (const [page, description] of indexableDescriptions) {
    const list = pagesByDescription.get(description) ?? [];
    list.push(page);
    pagesByDescription.set(description, list);
  }
  const repeated = [...pagesByDescription.entries()].filter(([, pages]) => pages.length > 1);
  for (const [description, pages] of repeated) {
    addError(
      `Identical meta description on ${pages.length} indexable pages (${pages.slice(0, 3).join(', ')}): "${description.slice(0, 70)}…"`
    );
  }
}

if (errors.length) {
  console.error(`Prerender SEO audit failed (${errors.length} issue(s)):\n- ${errors.join('\n- ')}`);
  process.exitCode = 1;
} else {
  console.log(
    `Prerender SEO audit passed: ${htmlFiles.length} HTML files, ${sitemapUrls.length} sitemap URLs, ` +
      `${site.isPreview ? 'preview safeguards' : 'canonical, indexation, and internal-link checks'}.`
  );
}
